class SummaryChain:
    def __init__(self) -> None:
        self.opened: list[str] = []
        self.opened_esmry: list[str] = []
        self._cases: dict[str, tuple[bytes, bytes]] = {}
        self._esmrys: dict[str, bytes] = {}

    def add(
        self,
        name: str,
        smspec: Smspec,
        unsmry: Unsmry,
    ) -> "SummaryChain":
        return self.add_entries(name, smspec.to_smry(), unsmry.to_smry())

    def add_entries(
        self,
        name: str,
        smspec_entries: list[tuple[str, Any]],
        unsmry_entries: list[tuple[str, Any]],
    ) -> "SummaryChain":
        contents = []
        for entries in (smspec_entries, unsmry_entries):
            buffer = BytesIO()
            resfo.write(buffer, entries, resfo.Format.UNFORMATTED)
            contents.append(buffer.getvalue())
        self._cases[name] = (contents[0], contents[1])
        return self

    def add_esmry(self, name: str, esmry: Esmry) -> "SummaryChain":
        buffer = BytesIO()
        esmry.to_file(buffer)
        self._esmrys[name] = buffer.getvalue()
        return self

    def frame(self, case: str, **kwargs: Any) -> pd.DataFrame:
        with self._patched():
            return summary_pandas_frame(case, **kwargs)

    def meta(self, case: str) -> dict[str, dict[str, Any]]:
        with self._patched():
            return summary_meta(case)

    def _patched(self) -> Any:
        """We patch the reader constructors so that we can
        inject the bytes contents in self._cases and self._esmrys and avoid
        writing to file in the unit tests
        """
        stack = ExitStack()
        stack.enter_context(
            mock.patch("res2df._summary_pandas_frame.SummaryReader", self)
        )
        stack.enter_context(
            mock.patch("res2df._summary_pandas_frame.EsmryReader", self.esmry_reader)
        )
        return stack

    def esmry_reader(self, *, case_path: str) -> EsmryReader:
        name = str(case_path)
        if name not in self._esmrys:
            raise FileNotFoundError(name)
        self.opened_esmry.append(name)
        contents = self._esmrys[name]
        return EsmryReader(esmry=lambda: BytesIO(contents))

    def __call__(self, *, case_path: str | os.PathLike[str]) -> SummaryReader:
        name = os.fspath(case_path)
        self.opened.append(name)
        if name not in self._cases:
            raise FileNotFoundError(name)
        smspec, unsmry = self._cases[name]
        return SummaryReader(
            smspec=lambda: BytesIO(smspec), summaries=[lambda: BytesIO(unsmry)]
        )


def one_summary(smspec: Smspec, unsmry: Unsmry) -> SummaryChain:
    return SummaryChain().add("CASE", smspec, unsmry)


def frame_of(smspec: Smspec, unsmry: Unsmry, **kwargs: Any) -> pd.DataFrame:
    return one_summary(smspec, unsmry).frame("CASE", **kwargs)


def keys_of(smspec: Smspec) -> list[str]:
    return list(smspec.summary_keys())[1:]  # The first keyword is TIME


def raw_values(unsmry: Unsmry) -> np.ndarray:
    """One row per ministep, the first column being TIME."""
    return np.array(
        [ms.params for step in unsmry.steps for ms in step.ministeps],
        dtype=np.float32,
    ).astype(np.float64)


def raw_seconds(smspec: Smspec, unsmry: Unsmry) -> np.ndarray:
    """The time of each ministep in seconds since epoch.

    The time of day of the start date is ignored, and the fractions of seconds
    are dropped (rounding towards zero, so towards later times before 1970).
    """
    start = smspec.start_date.to_datetime().replace(
        hour=0, minute=0, second=0, microsecond=0
    )
    unit = 3600 if smspec.units[0].strip() == "HOURS" else 24 * 3600
    start_seconds = (start - _EPOCH) // timedelta(seconds=1)
    return np.trunc(start_seconds + raw_values(unsmry)[:, 0] * unit).astype(np.int64)


def as_datetime(seconds: int) -> datetime:
    return _EPOCH + timedelta(seconds=int(seconds))


def raw_index(smspec: Smspec, unsmry: Unsmry) -> pd.DatetimeIndex:
    return pd.DatetimeIndex(
        [as_datetime(s) for s in raw_seconds(smspec, unsmry)]
    ).as_unit("us")


def with_steps(unsmry: Unsmry, keep: slice) -> Unsmry:
    ministeps = [ms for step in unsmry.steps for ms in step.ministeps][keep]
    return Unsmry([SummaryStep(i, [ms]) for i, ms in enumerate(ministeps)])


def with_restart(smspec: Smspec, restart: str) -> Smspec:
    return dataclasses.replace(smspec, restart=restart)


