@given(st.data(), summaries())
def test_that_wildcard_patterns_select_the_matching_keys_in_natural_order(
    data, generated
):
    smspec, unsmry = generated
    keys = keys_of(smspec)
    key = data.draw(st.sampled_from(keys))
    cut = data.draw(st.integers(min_value=0, max_value=len(key)))
    pattern = data.draw(
        st.sampled_from(
            [
                key[:cut] + "*",
                "*" + key[cut:],
                key[:cut] + "?" * (len(key) - cut),
                "[" + key[0] + "]" + key[1:],
            ]
        )
    )
    # Only the pattern "*" excludes TIME
    candidates = keys if pattern == "*" else [*keys, "TIME"]
    expected = natsorted(fnmatch.filter(candidates, pattern))
    assume(expected)
    assert list(frame_of(smspec, unsmry, column_keys=[pattern]).columns) == expected


