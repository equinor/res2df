    smspec, unsmry = summaries().example()
    file_format = resfo.Format.FORMATTED if formatted else resfo.Format.UNFORMATTED
    prefix = "F" if formatted else ""
    smspec.to_file(tmp_path / f"CASE.{prefix}SMSPEC", file_format)
    unsmry.to_file(tmp_path / f"CASE.{prefix}UNSMRY", file_format)
    pd.testing.assert_frame_equal(
        summary_pandas_frame(tmp_path / "CASE"),
        frame_of(smspec, unsmry),
        check_exact=True,
    )
    assert summary_meta(tmp_path / "CASE") == frame_of(smspec, unsmry).attrs["meta"]
    with pytest.raises(FileNotFoundError):
        summary_pandas_frame(tmp_path / "MISSING")


