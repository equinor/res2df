@given(st.data(), summaries())
def test_that_raw_times_are_cropped_to_the_start_and_end_dates(data, generated):
    smspec, unsmry = generated
    seconds = raw_seconds(smspec, unsmry)
    first, last = as_datetime(int(seconds[0])), as_datetime(int(seconds[-1]))
    dates = st.dates(first.date(), last.date())
    start = data.draw(st.none() | dates)
    end = data.draw(st.none() | dates)
    if start is not None and end is not None:
        assume(start < end)

    frame = frame_of(smspec, unsmry, time_index="raw", start_date=start, end_date=end)

    start_s = (
        None
        if start is None
        else int(
            (datetime.combine(start, datetime.min.time()) - _EPOCH).total_seconds()
        )
    )
    end_s = (
        None
        if end is None
        else int((datetime.combine(end, datetime.min.time()) - _EPOCH).total_seconds())
    )
    inside = [
        i
        for i, s in enumerate(seconds)
        if (start_s is None or s > start_s) and (end_s is None or s < end_s)
    ]
    expected_seconds = (
        ([] if start_s is None else [start_s])
        + [int(seconds[i]) for i in inside]
        + ([] if end_s is None else [end_s])
    )
    assert list(frame.index) == [as_datetime(s) for s in expected_seconds]
    offset = 0 if start_s is None else 1
    np.testing.assert_array_equal(
        frame.to_numpy()[offset : offset + len(inside)],
        raw_values(unsmry)[inside, 1:],
    )


