@given(summaries(), st.data())
def test_that_a_key_occurring_twice_gives_two_columns_with_the_last_values(
    generated, data
):
    smspec, unsmry = generated
    source = data.draw(st.integers(min_value=1, max_value=len(smspec.keywords) - 1))

    def repeated(values: list[Any] | None) -> list[Any] | None:
        return None if values is None else [*values, values[source]]

    duplicated = dataclasses.replace(
        smspec,
        num_keywords=smspec.num_keywords + 1,
        keywords=repeated(smspec.keywords),
        well_names=repeated(smspec.well_names),
        region_numbers=repeated(smspec.region_numbers),
        units=repeated(smspec.units),
        lgrs=repeated(smspec.lgrs),
        numlx=repeated(smspec.numlx),
        numly=repeated(smspec.numly),
        numlz=repeated(smspec.numlz),
    )
    doubled = Unsmry(
        [
            SummaryStep(
                step.seqnum,
                [
                    SummaryMiniStep(ms.mini_step, [*ms.params, ms.params[source] * 2])
                    for ms in step.ministeps
                ],
            )
            for step in unsmry.steps
        ]
    )
    key = keys_of(smspec)[source - 1]
    frame = frame_of(duplicated, doubled)
    assert list(frame.columns) == [*keys_of(smspec), key]
    last = raw_values(doubled)[:, -1]
    for column in np.atleast_2d(frame[key].to_numpy().T):
        np.testing.assert_array_equal(column, last)
    assert list(frame_of(duplicated, doubled, column_keys=[key]).columns) == [key]


meta_keys = ["FOPT", "FOPR", "FOPRH", "WOPR", "WOPT", "BPR", "LWOPR", "GWCT"]


@given(smspecs(sum_keys=st.just(meta_keys)))
def test_that_the_metadata_describes_each_column(smspec):
    assume(len(set(smspec.summary_keys())) == len(smspec.keywords))
    unsmry = Unsmry(
        [SummaryStep(0, [SummaryMiniStep(0, [0.0] * len(smspec.keywords))])]
    )
    meta = frame_of(smspec, unsmry).attrs["meta"]
    assert list(meta) == keys_of(smspec)
    for index, key in enumerate(keys_of(smspec), start=1):
        variable = smspec.keywords[index].strip()
        entry = meta[key]
        assert entry["keyword"] == variable
        assert entry["unit"] == smspec.units[index].strip()
        assert entry["is_rate"] == is_rate(variable)
        assert entry["is_total"] == (variable in ("FOPT", "WOPT"))
        assert entry["is_historical"] == (variable == "FOPRH")
        if variable in ("WOPR", "WOPT", "LWOPR", "GWCT"):
            assert entry["wgname"] == smspec.well_names[index].strip()
        else:
            assert entry["wgname"] is None
        if variable == "BPR":
            assert entry["get_num"] == smspec.region_numbers[index]
        elif variable == "LWOPR":
            assert entry["get_num"] == 0


