@given(st.data(), simple_interpolation_summaries)
def test_that_non_rates_are_linearly_interpolated_between_times(data, generated):
    smspec, unsmry = generated
    seconds, values = raw_seconds(smspec, unsmry), raw_values(unsmry)
    i = data.draw(st.integers(min_value=0, max_value=len(seconds) - 2))
    request = data.draw(
        st.integers(min_value=int(seconds[i]) + 1, max_value=int(seconds[i + 1]) - 1)
    )
    weight = (request - seconds[i]) / (seconds[i + 1] - seconds[i])
    frame = frame_of(smspec, unsmry, time_index=[as_datetime(request)])
    for key in ("FOPT", "FGPT"):
        column = keys_of(smspec).index(key) + 1
        expected = values[i, column] * (1 - weight) + values[i + 1, column] * weight
        np.testing.assert_allclose(frame[key].iloc[0], expected, rtol=1e-9)


